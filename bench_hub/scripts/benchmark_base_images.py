from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = Path(__file__).resolve().with_name("benchmark_base_images.txt")
DEFAULT_PULL_SCRIPT = Path(__file__).resolve().with_name("pull_benchmark_base_images.sh")

FROM_PATTERN = re.compile(r"^\s*FROM\s+([^\s]+)", re.IGNORECASE)
DOCKER_IMAGE_PATTERN = re.compile(r'docker-image://([^\s"\)]+)')
VARIABLE_START_PATTERN = re.compile(r'variable\s+"([^"]+)"\s*\{')
DEFAULT_PATTERN = re.compile(r'default\s*=\s*"([^"]+)"')
VARIABLE_REF_PATTERN = re.compile(r"\$\{([A-Z0-9_]+)\}")


def collect_autopenbench_images(project_root: str | Path) -> list[str]:
    root = Path(project_root)
    docker_root = root / "bench_hub" /"benchmarks" / "autopenbench"
    images: set[str] = set()

    for dockerfile in iter_dockerfiles(docker_root):
        for line in dockerfile.read_text(encoding="utf-8", errors="replace").splitlines():
            match = FROM_PATTERN.match(line)
            if not match:
                continue
            images.add(match.group(1))

    return sorted(images)


def collect_cvebench_images(project_root: str | Path) -> list[str]:
    root = Path(project_root)
    cvebench_root = root / "bench_hub" /"benchmarks" / "cvebench" / "src"
    variables = load_cvebench_variables(cvebench_root)
    images: set[str] = set()

    for hcl_path in sorted(cvebench_root.rglob("*.hcl")):
        text = hcl_path.read_text(encoding="utf-8", errors="replace")
        for match in DOCKER_IMAGE_PATTERN.finditer(text):
            resolved = resolve_variables(match.group(1), variables)
            if resolved:
                images.add(resolved)

    return sorted(images)


def render_report(*, autopenbench_images: list[str], cvebench_images: list[str]) -> str:
    combined_images = sorted(set(autopenbench_images) | set(cvebench_images))

    sections = [
        "# Benchmark Base Images",
        "",
        "# Auto-generated by scripts/benchmark_base_images.py",
        "",
        f"## AutoPenBench ({len(autopenbench_images)})",
        *autopenbench_images,
        "",
        f"## CVEBench ({len(cvebench_images)})",
        *cvebench_images,
        "",
        f"## Combined ({len(combined_images)})",
        *combined_images,
        "",
    ]
    return "\n".join(sections)


def render_pull_script(*, autopenbench_images: list[str], cvebench_images: list[str]) -> str:
    combined_images = sorted(set(autopenbench_images) | set(cvebench_images))
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Auto-generated by scripts/benchmark_base_images.py",
        "",
    ]
    for image in combined_images:
        lines.append(f'docker pull "{image}"')
    lines.append("")
    return "\n".join(lines)


def write_artifacts(
    *,
    project_root: str | Path = ROOT,
    report_output_path: str | Path = DEFAULT_OUTPUT,
    pull_script_output_path: str | Path = DEFAULT_PULL_SCRIPT,
) -> tuple[str, str]:
    autopenbench_images = collect_autopenbench_images(project_root)
    cvebench_images = collect_cvebench_images(project_root)
    report = render_report(
        autopenbench_images=autopenbench_images,
        cvebench_images=cvebench_images,
    )
    pull_script = render_pull_script(
        autopenbench_images=autopenbench_images,
        cvebench_images=cvebench_images,
    )
    Path(report_output_path).write_text(report, encoding="utf-8")
    Path(pull_script_output_path).write_text(pull_script, encoding="utf-8")
    return report, pull_script


def iter_dockerfiles(root: Path):
    if not root.exists():
        return
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if path.name == "Dockerfile" or path.name.startswith("Dockerfile."):
            yield path


def load_cvebench_variables(cvebench_root: Path) -> dict[str, str]:
    variables: dict[str, str] = {}
    for hcl_path in sorted(cvebench_root.rglob("*.hcl")):
        text = hcl_path.read_text(encoding="utf-8", errors="replace")
        variables.update(parse_string_defaults(text))
    return variables


def parse_string_defaults(text: str) -> dict[str, str]:
    variables: dict[str, str] = {}
    for match in VARIABLE_START_PATTERN.finditer(text):
        name = match.group(1)
        block = extract_brace_block(text, match.end() - 1)
        default_match = DEFAULT_PATTERN.search(block)
        if default_match:
            variables[name] = default_match.group(1)
    return variables


def extract_brace_block(text: str, brace_start: int) -> str:
    depth = 0
    for index in range(brace_start, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[brace_start : index + 1]
    return text[brace_start:]


def resolve_variables(raw_value: str, variables: dict[str, str]) -> str:
    resolved = raw_value
    for _ in range(10):
        matches = VARIABLE_REF_PATTERN.findall(resolved)
        if not matches:
            return resolved
        next_value = resolved
        changed = False
        for name in matches:
            replacement = variables.get(name)
            if replacement is None:
                continue
            next_value = next_value.replace(f"${{{name}}}", replacement)
            changed = True
        resolved = next_value
        if not changed:
            return resolved
    return resolved


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Collect benchmark base images for AutoPenBench and CVEBench")
    parser.add_argument(
        "--project-root",
        default=str(ROOT),
        help="Project root that contains benchmarks/",
    )
    parser.add_argument(
        "--output",
        default=str(DEFAULT_OUTPUT),
        help="Path to write the generated report",
    )
    parser.add_argument(
        "--pull-script-output",
        default=str(DEFAULT_PULL_SCRIPT),
        help="Path to write the generated docker pull script",
    )
    return parser


def main() -> None:
    args = build_parser().parse_args()
    write_artifacts(
        project_root=args.project_root,
        report_output_path=args.output,
        pull_script_output_path=args.pull_script_output,
    )
    autopenbench_images = collect_autopenbench_images(args.project_root)
    cvebench_images = collect_cvebench_images(args.project_root)
    combined_count = len(set(autopenbench_images) | set(cvebench_images))
    print(
        "Wrote "
        f"{args.output} and {args.pull_script_output} "
        f"with {combined_count} combined images."
    )


if __name__ == "__main__":
    main()
